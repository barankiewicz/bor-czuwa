import { openNoticeRow } from './stages.ts';
import { test, expect } from '@playwright/test';
import { answerHome, answerNow, heading, leaveCompass, save } from './stages.ts';

test('Back and Forward walk the completion steps and keep Draft identity', async ({ page, context }) => {
  await context.setGeolocation({ latitude: 52.1, longitude: 19.4, accuracy: 12 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Zapisz miejsce i czas' }).click();
  await expect(page.locator('#receipt')).toBeVisible();
  const savedUrl = page.url();
  await page.getByRole('button', { name: 'Człowiek z bronią', exact: true }).click();
  await expect(page.locator('.steps li')).toHaveText(['Co', 'Kiedy', 'Gdzie', 'Sprawdź']);
  await answerNow(page);
  await leaveCompass(page);
  await page.getByRole('button', { name: 'Zmień: Gdzie' }).click();
  await expect(heading(page, 'Gdzie widzisz człowieka z bronią?')).toBeVisible();
  await page.goBack();
  await expect(heading(page, 'Sprawdź i zapisz')).toBeVisible();
  await page.goBack();
  await expect(heading(page, 'Gdzie widzisz człowieka z bronią?')).toBeVisible();
  await page.goBack();
  await expect(heading(page, 'Kiedy to się stało?')).toBeVisible();
  await page.goBack();
  await expect(page.locator('#receipt')).toBeVisible();
  await expect(page.url()).toBe(savedUrl);
  await page.goBack();
  await expect(page.getByRole('button', { name: 'Zapisz miejsce i czas' })).toBeVisible();
  await page.goForward();
  await page.goForward();
  await page.goForward();
  await page.goForward();
  await expect(heading(page, 'Sprawdź i zapisz')).toBeVisible();
  await page.reload();
  await expect(heading(page, 'Sprawdź i zapisz')).toBeVisible();
  await expect(page.locator('.review-row').first()).toContainText('Człowiek z bronią');
  expect(page.url()).toContain('draft=');
});

test('record Back returns to opening context; deleted direct URL recovers in library', async ({ page, context }) => {
  await context.setGeolocation({ latitude: 52.1, longitude: 19.4, accuracy: 12 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Człowiek z bronią', exact: true }).click();
  await expect(heading(page, 'Kiedy to się stało?')).toBeVisible();
  const directUrl = page.url();
  await page.getByRole('button', { name: 'Dokończę później' }).click();
  await page.getByRole('button', { name: 'Moje zapisy' }).first().click();
  await expect(page.getByRole('heading', { name: 'Moje zapisy' })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 300 });
  const body = page.locator('.screen-body');
  await body.evaluate(element => { element.scrollTop = 80; });
  const libraryScroll = await body.evaluate(element => element.scrollTop);
  expect(libraryScroll).toBeGreaterThan(0);
  await page.getByRole('button', { name: /^Dokończ zgłoszenie/ }).evaluate(element => (element as HTMLElement).click());
  await expect(heading(page, 'Kiedy to się stało?')).toBeVisible();
  await page.getByRole('button', { name: 'Wróć', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Moje zapisy' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Moje zapisy' })).toBeFocused();
  await expect.poll(() => body.evaluate(element => element.scrollTop)).toBe(libraryScroll);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(directUrl);
  await expect(heading(page, 'Kiedy to się stało?')).toBeVisible();
  await page.getByRole('button', { name: 'Bór czuwa' }).click();
  await page.getByRole('button', { name: 'Moje zapisy' }).first().click();
  await page.getByRole('button', { name: 'Usuń szkic' }).click();
  await page.getByRole('group', { name: 'Usunąć szkic?' }).getByRole('button', { name: 'Usuń', exact: true }).click();
  await expect(page.getByRole('button', { name: /^Dokończ zgłoszenie/ })).toHaveCount(0);
  await page.goto(directUrl);
  await expect(page.getByRole('heading', { name: 'Moje zapisy' })).toBeVisible();
  await expect(page.getByRole('alert')).toContainText('Nie znaleziono szkicu');
});

test('Report and Notice routes restore without signer details in history', async ({ page, context }) => {
  await context.setGeolocation({ latitude: 52.1, longitude: 19.4, accuracy: 12 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Człowiek z bronią', exact: true }).click();
  await answerNow(page);
  await leaveCompass(page);
  await answerHome(page, false);
  await save(page);
  await expect(page.getByRole('heading', { name: 'Zgłoszenie', exact: true })).toBeVisible();
  const reportUrl = page.url();
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Co się stało?' })).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.goForward();
  await expect(page.getByRole('heading', { name: 'Zgłoszenie', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Zgłoszenie', exact: true })).toBeVisible();
  expect(page.url()).toBe(reportUrl);

  await page.getByRole('button', { name: 'Przygotuj powiadomienie' }).click();
  await expect(page.getByRole('heading', { name: 'Do kogo napisać?' })).toBeVisible();
  await expect(page.getByText('Sprawdzam właściwe urzędy…')).toHaveCount(0);
  // The first in the document: a bottom copy may still be folding away.
  const opener = page.getByRole('button', { name: /^Wybierz (inną )?jednostkę po nazwie$/ }).first();
  if (await opener.isVisible()) await opener.click();
  await page.getByLabel('Nazwa lub miejscowość').fill('Monkach');
  await page.getByRole('button', { name: /Komenda Powiatowa Policji w Mońkach/ }).click();
  await page.getByRole('button', { name: 'Dalej: podpis' }).click();
  await page.getByRole('radio', { name: 'Z podpisem' }).check();
  await page.getByLabel('Imię i nazwisko').fill('Jan Testowy');
  await page.getByLabel('Adres do korespondencji').fill('ul. Testowa 1');
  await page.getByRole('button', { name: 'Przygotuj powiadomienia' }).click();
  await expect(page.getByRole('heading', { name: 'Komenda Powiatowa Policji w Mońkach' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Komenda Powiatowa Policji w Mońkach' })).toBeVisible();
  const noticeUrl = page.url();
  expect(noticeUrl).not.toContain('Jan');
  expect(JSON.stringify(await page.evaluate(() => history.state))).not.toContain('Jan');
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Do kogo napisać?' })).toBeVisible();
  await page.goForward();
  await expect(page.getByRole('heading', { name: 'Komenda Powiatowa Policji w Mońkach' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Komenda Powiatowa Policji w Mońkach' })).toBeVisible();
});
